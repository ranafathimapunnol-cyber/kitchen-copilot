"""Excel and PDF renderings of the tabular reports (Stage 9).

They lay out the dictionary from tabular_reports.build — the figures the
screen shows — and recalculate nothing. Fonts, money formats and the page
footer follow the purchases report (app/services/report_exports.py).
"""

import re
from decimal import Decimal
from io import BytesIO
from xml.sax.saxutils import escape

from app.services.report_exports import FONT_BOLD, FONT_REGULAR, _register_fonts, format_day, format_inr, generated_text


def period_line(report: dict) -> str:
    if report.get("period"):
        p = report["period"]
        return f"{format_day(p['date_from'])} – {format_day(p['date_to'])}"
    return f"As of {format_day(report['as_of'])}" if report.get("as_of") else ""


def header_rows(report: dict, exported_by: str) -> list[tuple[str, str]]:
    rows = [("Campus", report["campus"]["name"] or f"Campus #{report['campus']['id']}"),
            ("Period" if report.get("period") else "As of", period_line(report))]
    if report.get("comparison"):
        prev = report["comparison"]["previous"]
        rows.append(("Compared with", f"{format_day(prev['date_from'])} – {format_day(prev['date_to'])}"))
    rows += [(f["label"], f["value"] or "") for f in report["filters"]] or [("Filters", "None")]
    rows.append(("Generated", generated_text(report, exported_by)))
    return rows


def cell_text(column: dict, row: dict) -> str:
    value = row.get(column["key"])
    if value is None or value == "":
        return "—" if column["kind"] in ("money", "percent") else ""
    kind = column["kind"]
    if kind == "money":
        return format_inr(value)
    if kind == "percent":
        return f"{value}%"
    if kind == "qty":
        unit = row.get(column["unit_key"]) if column.get("unit_key") else None
        number = Decimal(str(value)).normalize()
        text = format(number, "f") if number != 0 else "0"
        return f"{text} {unit}".strip() if unit else text
    if kind == "date":
        return format_day(str(value))
    return str(value)


def total_text(total: dict) -> str:
    value = total.get("value")
    if value is None:
        return "Not comparable" if total.get("kind") == "percent" else "—"
    if total.get("kind") == "money":
        return format_inr(value)
    if total.get("kind") == "percent":
        return f"{value}%"
    if total.get("kind") == "qty":
        number = Decimal(str(value)).normalize()
        return f"{format(number, 'f') if number != 0 else '0'} {total.get('unit') or ''}".strip()
    return str(value)


def export_filename(report: dict, extension: str) -> str:
    name = report["key"].replace("_", "-")
    if report.get("period"):
        name += f"_{report['period']['date_from']}_{report['period']['date_to']}"
    elif report.get("as_of"):
        name += f"_as-of-{report['as_of']}"
    for f in report["filters"]:
        if f["label"] in ("Supplier", "Category", "Item", "Meal session") and f["value"]:
            slug = re.sub(r"[^a-z0-9]+", "-", str(f["value"]).lower()).strip("-")[:30]
            if slug:
                name += f"_{slug}"
    return f"{name}.{extension}"


def render_xlsx(report: dict, exported_by: str) -> bytes:
    import xlsxwriter

    buffer = BytesIO()
    workbook = xlsxwriter.Workbook(buffer, {"in_memory": True})
    workbook.set_properties({"title": report["title"], "author": exported_by, "company": report["campus"]["name"] or "",
                             "comments": "Generated by Kitchen Copilot."})
    title = workbook.add_format({"bold": True, "font_size": 14})
    label = workbook.add_format({"bold": True, "font_color": "#475569"})
    head = workbook.add_format({"bold": True, "bg_color": "#F1F5F9", "bottom": 1, "text_wrap": True, "valign": "top"})
    money = workbook.add_format({"num_format": '"₹"#,##0.00'})
    number = workbook.add_format({"num_format": "#,##0.###"})
    note = workbook.add_format({"font_color": "#64748B", "italic": True})
    bold = workbook.add_format({"bold": True})
    sheet = workbook.add_worksheet("Report")
    row = 0
    sheet.write(row, 0, report["title"], title)
    row += 1
    for key, value in header_rows(report, exported_by):
        sheet.write(row, 0, key, label)
        sheet.write(row, 1, value)
        row += 1
    row += 1
    columns = []
    for column in report["columns"]:
        columns.append(column)
        if column["kind"] == "qty" and column.get("unit_key"):
            columns.append({"key": column["unit_key"], "label": "Unit", "kind": "text"})
    for index, column in enumerate(columns):
        sheet.write(row, index, column["label"], head)
        sheet.set_column(index, index, 14 if column["kind"] != "text" else 22)
    header_row = row
    row += 1
    for record in report["rows"]:
        for index, column in enumerate(columns):
            value = record.get(column["key"])
            if value is None or value == "":
                continue
            if column["kind"] in ("money", "qty", "number", "percent"):
                try:
                    sheet.write_number(row, index, float(Decimal(str(value))), money if column["kind"] == "money" else number)
                    continue
                except Exception:  # noqa: BLE001 - non-numeric text stays text
                    pass
            sheet.write(row, index, str(value))
        row += 1
    if report["rows"]:
        sheet.autofilter(header_row, 0, row - 1, len(columns) - 1)
    else:
        sheet.write(row, 0, "No records for these filters.", note)
        row += 1
    row += 1
    for total in report["totals"]:
        sheet.write(row, 0, total["label"], bold)
        sheet.write(row, 1, total_text(total))
        row += 1
    row += 1
    for line in report["notes"]:
        sheet.write(row, 0, line, note)
        row += 1
    sheet.freeze_panes(header_row + 1, 0)
    workbook.close()
    return buffer.getvalue()


def render_pdf(report: dict, exported_by: str) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    _register_fonts()
    ink, muted, rule, band = (colors.HexColor(c) for c in ("#0F172A", "#64748B", "#CBD5E1", "#F1F5F9"))
    base = ParagraphStyle("base", fontName=FONT_REGULAR, fontSize=7.5, leading=9.5, textColor=ink)
    small = ParagraphStyle("small", parent=base, fontSize=7, leading=9, textColor=muted)
    title_style = ParagraphStyle("title", parent=base, fontName=FONT_BOLD, fontSize=15, leading=19)
    story = [Paragraph(escape(report["title"]), title_style), Spacer(1, 3 * mm)]
    meta = Table([[Paragraph(f"<b>{escape(k)}</b>", base), Paragraph(escape(str(v)), base)]
                  for k, v in header_rows(report, exported_by)], colWidths=[34 * mm, 220 * mm], hAlign="LEFT")
    meta.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                              ("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1)]))
    story += [meta, Spacer(1, 4 * mm)]
    columns = report["columns"]
    if report["rows"]:
        width = (landscape(A4)[0] - 24 * mm) / len(columns)
        data = [[Paragraph(f"<b>{escape(c['label'])}</b>", base) for c in columns]]
        data += [[Paragraph(escape(cell_text(c, r)), base) for c in columns] for r in report["rows"]]
        table = Table(data, colWidths=[width] * len(columns), repeatRows=1, hAlign="LEFT")
        table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), band), ("LINEBELOW", (0, 0), (-1, 0), 0.6, rule),
                                   ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 2),
                                   ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
        story.append(table)
    else:
        story.append(Paragraph("No records for these filters.", base))
    story.append(Spacer(1, 4 * mm))
    if report["totals"]:
        totals = Table([[Paragraph(f"<b>{escape(t['label'])}</b>", base), Paragraph(escape(total_text(t)), base)]
                        for t in report["totals"]], colWidths=[90 * mm, 50 * mm], hAlign="LEFT")
        totals.setStyle(TableStyle([("LINEABOVE", (0, 0), (-1, 0), 0.6, rule), ("TOPPADDING", (0, 0), (-1, -1), 1),
                                    ("BOTTOMPADDING", (0, 0), (-1, -1), 1)]))
        story += [totals, Spacer(1, 3 * mm)]
    story += [Paragraph(escape(line), small) for line in report["notes"]]
    footer = f"Kitchen Copilot · {report['title']} · {period_line(report)}"

    def on_page(canvas, document):
        canvas.saveState()
        canvas.setFont(FONT_REGULAR, 7)
        canvas.setFillColor(muted)
        canvas.drawString(12 * mm, 8 * mm, footer)
        canvas.drawRightString(landscape(A4)[0] - 12 * mm, 8 * mm, f"Page {document.page}")
        canvas.restoreState()

    buffer = BytesIO()
    SimpleDocTemplate(buffer, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm, topMargin=12 * mm,
                      bottomMargin=14 * mm, title=report["title"], author=exported_by).build(
        story, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()

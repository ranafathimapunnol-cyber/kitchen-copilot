def render_pdf(report: dict, exported_by: str) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    _register_fonts()
    costs = report["costs_visible"]
    ink = colors.HexColor("#0F172A")
    muted = colors.HexColor("#64748B")
    rule = colors.HexColor("#CBD5E1")
    band = colors.HexColor("#F1F5F9")
    base = ParagraphStyle("base", fontName=FONT_REGULAR, fontSize=8, leading=10.5, textColor=ink)
    small = ParagraphStyle("small", parent=base, fontSize=7.5, leading=10, textColor=muted)
    title_style = ParagraphStyle("title", parent=base, fontName=FONT_BOLD, fontSize=16, leading=20)
    heading_style = ParagraphStyle("heading", parent=base, fontName=FONT_BOLD, fontSize=11, leading=14,
                                   spaceBefore=8, spaceAfter=4)

    def style(numeric_from: int) -> TableStyle:
        return TableStyle([
            ("FONTNAME", (0, 0), (-1, -1), FONT_REGULAR), ("FONTSIZE", (0, 0), (-1, -1), 7.5),
            ("TEXTCOLOR", (0, 0), (-1, -1), ink), ("FONTNAME", (0, 0), (-1, 0), FONT_BOLD),
            ("BACKGROUND", (0, 0), (-1, 0), band), ("LINEBELOW", (0, 0), (-1, 0), 0.6, rule),
            ("ALIGN", (numeric_from, 0), (-1, -1), "RIGHT"), ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ])

    story = [Paragraph(TITLE, title_style), Spacer(1, 3 * mm)]
    meta = Table([[Paragraph(f"<b>{escape(k)}</b>", base), Paragraph(escape(v), base)]
                  for k, v in header_rows(report, exported_by)], colWidths=[34 * mm, 200 * mm], hAlign="LEFT")
    meta.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 1),
                              ("BOTTOMPADDING", (0, 0), (-1, -1), 1), ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    story += [meta, Spacer(1, 3 * mm)]

    if costs:
        totals = report["cost_totals"]
        money_table = Table([
            ["Cost", "Amount"],
            ["Purchase expenditure (linked bill lines)", format_inr(totals["billed_cost"])],
            ["Planned cost (orders; not expenditure)", format_inr(totals["planned_cost"])],
            ["Order lines without a linked bill line", str(totals["lines_without_bill"])],
        ], colWidths=[90 * mm, 40 * mm], hAlign="LEFT")
        money_table.setStyle(style(1))
        story += [Paragraph("Costs", heading_style), money_table]

    story.append(Paragraph("By item", heading_style))
    if report["by_item"]:
        head = ["Item", "Unit"] + [n for _k, n in QTY_COLUMNS] + (["Planned", "Billed"] if costs else [])
        body = [[Paragraph(escape(g["item_name"] or ""), base), g["unit_symbol"] or ""]
                + [qty(g[k]) for k, _n in QTY_COLUMNS]
                + ([format_inr(g["planned_cost"]), format_inr(g["billed_cost"])] if costs else [])
                for g in report["by_item"]]
        widths = [40 * mm, 12 * mm] + [17 * mm] * len(QTY_COLUMNS) + ([24 * mm, 24 * mm] if costs else [])
        table = Table([head] + body, colWidths=widths, repeatRows=1, hAlign="LEFT")
        table.setStyle(style(2))
        story.append(table)
        story.append(Paragraph("Totals by unit", heading_style))
        unit_rows = [["Unit", "Lines"] + [n for _k, n in QTY_COLUMNS]] + [
            [g["unit_symbol"] or "", str(g["lines"])] + [qty(g[k]) for k, _n in QTY_COLUMNS]
            for g in report["totals_by_unit"]]
        units_table = Table(unit_rows, colWidths=[20 * mm, 12 * mm] + [17 * mm] * len(QTY_COLUMNS), hAlign="LEFT")
        units_table.setStyle(style(1))
        story.append(units_table)

        story.append(Paragraph("Lines", heading_style))
        head = ["Meal", "Order", "Item", "Unit", "Ordered", "Received", "Rejected", "Accepted", "Distributed",
                "Remaining", "Status"] + (["Billed"] if costs else [])
        body = [[Paragraph(escape(f"{format_day(e['meal_date'])} {e['meal_session_name'] or ''}"), base),
                 Paragraph(escape(f"{e['order_number']} · {e['supplier_name'] or ''}"), base),
                 Paragraph(escape(e["item_name"] or ""), base), e["unit_symbol"] or "",
                 qty(e["ordered_quantity"]), qty(e["received_quantity"]), qty(e["rejected_quantity"]),
                 qty(e["accepted_quantity"]), qty(e["distributed_quantity"]), qty(e["remaining_quantity"]),
                 Paragraph(escape(STATUS_LABELS.get(e["status"], e["status"])), base)]
                + ([format_inr(e["billed_cost"]) if e["billed_cost"] is not None else "—"] if costs else [])
                for e in report["lines"]]
        widths = [30 * mm, 38 * mm, 34 * mm, 11 * mm] + [16 * mm] * 6 + [30 * mm] + ([22 * mm] if costs else [])
        lines_table = Table([head] + body, colWidths=widths, repeatRows=1, hAlign="LEFT")
        lines_table.setStyle(style(4))
        story.append(lines_table)
    else:
        story.append(Paragraph("No outsourced food ordered in this period.", base))

    story.append(Spacer(1, 4 * mm))
    story += [Paragraph(escape(line), small) for line in basis_lines(report)]

    footer = f"Kitchen Copilot · {TITLE} · {period_text(report)} · {filter_text(report)}"

    def on_page(canvas, document):
        canvas.saveState()
        canvas.setFont(FONT_REGULAR, 7.5)
        canvas.setFillColor(muted)
        canvas.drawString(12 * mm, 8 * mm, footer)
        canvas.drawRightString(landscape(A4)[0] - 12 * mm, 8 * mm, f"Page {document.page}")
        canvas.restoreState()

    buffer = BytesIO()
    document = SimpleDocTemplate(buffer, pagesize=landscape(A4), leftMargin=12 * mm, rightMargin=12 * mm,
                                 topMargin=12 * mm, bottomMargin=14 * mm, title=TITLE, author=exported_by)
    document.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buffer.getvalue()

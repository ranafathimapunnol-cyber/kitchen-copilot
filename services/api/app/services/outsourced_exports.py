"""Excel and PDF renderings of the outsourced-food report (OUT02, AT04).

Both take the dictionary from outsourced.build_report, the data the screen
shows, and only lay it out; nothing is recalculated. Cost columns appear
only when the report carries them (users with purchase_bill.read). The
shared helpers, fonts and file types are those of the purchases report
(app/services/report_exports.py).
"""

import re
from decimal import Decimal
from io import BytesIO
from xml.sax.saxutils import escape

from app.services.report_exports import (
    FONT_BOLD, FONT_REGULAR, _register_fonts, format_day, format_inr, generated_text, money,
)

TITLE = "Outsourced food"

STATUS_LABELS = {
    "RECONCILED": "Reconciled",
    "PENDING_MEAL_RECORD": "Waiting for meal record",
    "DISTRIBUTION_NOT_RECORDED": "Distribution not recorded",
    "LEFTOVERS_NOT_CLASSIFIED": "Leftovers not classified",
    "NOT_DELIVERED": "Not delivered",
    "ALL_REJECTED": "All rejected",
}

QTY_COLUMNS = (
    ("ordered_quantity", "Ordered"), ("received_quantity", "Received"), ("rejected_quantity", "Rejected"),
    ("accepted_quantity", "Accepted"), ("distributed_quantity", "Distributed"),
    ("remaining_quantity", "Remaining"), ("retained_quantity", "Retained"),
    ("returned_to_supplier_quantity", "Returned"), ("wasted_quantity", "Wasted"),
    ("disposed_quantity", "Disposed"),
)


def period_text(report: dict) -> str:
    period = report["period"]
    return f"{format_day(period['date_from'])} – {format_day(period['date_to'])}"


def filter_text(report: dict) -> str:
    f = report["filters"]
    parts = [f["supplier_name"] or "All suppliers", f["item_name"] or "All items",
             f["meal_session_name"] or "All meal sessions"]
    return " · ".join(parts)


def header_rows(report: dict, exported_by: str) -> list[tuple[str, str]]:
    f = report["filters"]
    return [
        ("Campus", report["campus"]["name"] or f"Campus #{report['campus']['id']}"),
        ("Period (meal date)", period_text(report)),
        ("Supplier", f["supplier_name"] or "All suppliers"),
        ("Item", f["item_name"] or "All items"),
        ("Meal session", f["meal_session_name"] or "All meal sessions"),
        ("Costs", "Included" if report["costs_visible"] else "Not included (no supplier-bill access)"),
        ("Generated", generated_text(report, exported_by)),
    ]


def basis_lines(report: dict) -> list[str]:
    basis = report["basis"]
    lines = [basis["orders"], basis["quantities"]]
    if report["costs_visible"]:
        lines.append(basis["costs"])
    lines.append(f"Rejected quantities: {basis['rejected']}")
    return lines


def qty(value: str) -> str:
    return format(Decimal(value).normalize(), "f") if Decimal(value) != 0 else "0"


def export_filename(report: dict, extension: str) -> str:
    period = report["period"]
    name = f"outsourced-food_{period['date_from']}_{period['date_to']}"
    for key in ("supplier_name", "item_name", "meal_session_name"):
        value = report["filters"][key]
        if value:
            slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")[:30]
            if slug:
                name += f"_{slug}"
    return f"{name}.{extension}"



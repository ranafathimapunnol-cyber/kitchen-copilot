def render_xlsx(report: dict, exported_by: str) -> bytes:
    import xlsxwriter

    costs = report["costs_visible"]
    buffer = BytesIO()
    workbook = xlsxwriter.Workbook(buffer, {"in_memory": True})
    workbook.set_properties({"title": TITLE, "subject": f"{period_text(report)} · {filter_text(report)}",
                             "author": exported_by, "company": report["campus"]["name"] or "",
                             "comments": "Generated by Kitchen Copilot."})
    title = workbook.add_format({"bold": True, "font_size": 14})
    label = workbook.add_format({"bold": True, "font_color": "#475569"})
    heading = workbook.add_format({"bold": True, "font_size": 12})
    column = workbook.add_format({"bold": True, "bg_color": "#F1F5F9", "bottom": 1, "text_wrap": True, "valign": "top"})
    column_right = workbook.add_format({"bold": True, "bg_color": "#F1F5F9", "bottom": 1, "align": "right",
                                        "text_wrap": True, "valign": "top"})
    note = workbook.add_format({"font_color": "#64748B", "italic": True})
    number = workbook.add_format({"num_format": "#,##0.###"})
    amount = workbook.add_format({"num_format": '"₹"#,##0.00'})
    date_format = workbook.add_format({"num_format": "dd mmm yyyy"})

    def as_number(value) -> float:
        return float(Decimal(value))

    # ---- Summary sheet ----
    sheet = workbook.add_worksheet("Summary")
    sheet.set_column(0, 0, 30)
    sheet.set_column(1, 1, 10)
    sheet.set_column(2, 12, 12)
    row = 0
    sheet.write(row, 0, TITLE, title)
    row += 1
    for key, value in header_rows(report, exported_by):
        sheet.write(row, 0, key, label)
        sheet.write(row, 1, value)
        row += 1
    if costs:
        row += 1
        sheet.write(row, 0, "Costs", heading)
        row += 1
        totals = report["cost_totals"]
        sheet.write(row, 0, "Purchase expenditure (linked bill lines)")
        sheet.write_number(row, 2, float(money(totals["billed_cost"])), amount)
        row += 1
        sheet.write(row, 0, "Planned cost (orders; not expenditure)")
        sheet.write_number(row, 2, float(money(totals["planned_cost"])), amount)
        row += 1
        sheet.write(row, 0, "Order lines without a linked bill line")
        sheet.write_number(row, 2, totals["lines_without_bill"])
        row += 1

    row += 1
    sheet.write(row, 0, "By item", heading)
    row += 1
    headers = ["Item", "Unit"] + [name for _k, name in QTY_COLUMNS] + (["Planned cost", "Billed cost"] if costs else [])
    for index, name in enumerate(headers):
        sheet.write(row, index, name, column if index < 2 else column_right)
    row += 1
    for group in report["by_item"]:
        sheet.write(row, 0, group["item_name"] or "")
        sheet.write(row, 1, group["unit_symbol"] or "")
        for index, (key, _n) in enumerate(QTY_COLUMNS, start=2):
            sheet.write_number(row, index, as_number(group[key]), number)
        if costs:
            sheet.write_number(row, 2 + len(QTY_COLUMNS), float(money(group["planned_cost"])), amount)
            sheet.write_number(row, 3 + len(QTY_COLUMNS), float(money(group["billed_cost"])), amount)
        row += 1
    if not report["by_item"]:
        sheet.write(row, 0, "No outsourced food ordered in this period.", note)
        row += 1

    row += 1
    sheet.write(row, 0, "Totals by unit", heading)
    row += 1
    for index, name in enumerate(["Unit", "Lines"] + [n for _k, n in QTY_COLUMNS]):
        sheet.write(row, index, name, column if index == 0 else column_right)
    row += 1
    for group in report["totals_by_unit"]:
        sheet.write(row, 0, group["unit_symbol"] or "")
        sheet.write_number(row, 1, group["lines"])
        for index, (key, _n) in enumerate(QTY_COLUMNS, start=2):
            sheet.write_number(row, index, as_number(group[key]), number)
        row += 1

    row += 1
    for line in basis_lines(report):
        sheet.write(row, 0, line, note)
        row += 1

    # ---- Lines sheet ----
    lines = workbook.add_worksheet("Lines")
    columns = ["Meal date", "Meal session", "Order", "Supplier", "Item", "Unit"] + [n for _k, n in QTY_COLUMNS] + [
        "Status"] + (["Rate", "Planned cost", "Billed cost", "Bill"] if costs else [])
    lines.set_column(0, 0, 12)
    lines.set_column(1, 5, 16)
    lines.set_column(6, 6 + len(QTY_COLUMNS), 11)
    lines.set_column(6 + len(QTY_COLUMNS), 6 + len(QTY_COLUMNS), 24)
    for index, name in enumerate(columns):
        lines.write(0, index, name, column if index < 6 or name in ("Status", "Bill") else column_right)
    from datetime import datetime as _dt
    for r, entry in enumerate(report["lines"], start=1):
        lines.write_datetime(r, 0, _dt.strptime(entry["meal_date"], "%Y-%m-%d"), date_format)
        lines.write(r, 1, entry["meal_session_name"] or "")
        lines.write(r, 2, entry["order_number"])
        lines.write(r, 3, entry["supplier_name"] or "")
        lines.write(r, 4, entry["item_name"] or "")
        lines.write(r, 5, entry["unit_symbol"] or "")
        for index, (key, _n) in enumerate(QTY_COLUMNS, start=6):
            lines.write_number(r, index, as_number(entry[key]), number)
        status_col = 6 + len(QTY_COLUMNS)
        lines.write(r, status_col, STATUS_LABELS.get(entry["status"], entry["status"]))
        if costs:
            lines.write_number(r, status_col + 1, float(Decimal(entry["unit_rate"])))
            lines.write_number(r, status_col + 2, float(money(entry["planned_cost"])), amount)
            if entry["billed_cost"] is not None:
                lines.write_number(r, status_col + 3, float(money(entry["billed_cost"])), amount)
            lines.write(r, status_col + 4, entry["bill_invoice_number"] or "")
    if report["lines"]:
        lines.autofilter(0, 0, len(report["lines"]), len(columns) - 1)
    lines.freeze_panes(1, 0)

    workbook.close()
    return buffer.getvalue()


